SELECT
   OCYC.Code AS 'Cycle Code', 
   OCYC.Name AS 'Cycle Name', 
   OCYC.Frequency AS 'Frequency', 
   OCYC.Day AS 'Day', 
   OCYC.Hour AS 'Hour', 
   OCYC.UserSign AS 'User Signature', 
   OCYC.NextDate AS 'Next Counting Date', 
   OCYC.Type AS 'Cycle Type', 
   OCYC.SubOption AS 'Suboption', 
   OCYC.Interval AS 'Interval', 
   OCYC.EndType AS 'Recurrence End Type', 
   OCYC.MaxOccur AS 'Max. Occurrences', 
   OCYC.SeEndDat AS 'Series End Date', 
   OCYC.Sunday AS 'Sunday', 
   OCYC.Monday AS 'Monday', 
   OCYC.Tuesday AS 'Tuesday', 
   OCYC.Wednesday AS 'Wednesday', 
   OCYC.Thursday AS 'Thursday', 
   OCYC.Friday AS 'Friday', 
   OCYC.Saturday AS 'Saturday', 
   OCYC.DayInMonth AS 'Repeat Day in Month', 
   OCYC.Week AS 'Repeat Week in Month', 
   OCYC.DayOfWeek AS 'Repeat Day of Week', 
   OCYC.Month AS 'Repeat Month'
FROM OCYC AS OCYC
