SELECT
   OLGT.UnitCode AS 'Unit Code', 
   OLGT.UnitDisply AS 'Unit Display', 
   OLGT.UnitName AS 'Unit Name', 
   OLGT.VolDisply AS 'Unit Code for Quantity Display', 
   OLGT.SizeInMM AS 'Unit Length in mm', 
   OLGT.Locked AS 'Locked', 
   OLGT.DataSource AS 'Data Source', 
   OLGT.UserSign AS 'User Signature'
FROM OLGT AS OLGT
