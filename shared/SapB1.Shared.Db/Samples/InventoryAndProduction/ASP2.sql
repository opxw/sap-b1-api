SELECT
   ASP2.ItemCode AS 'Item No.', 
   ASP2.CardCode AS 'BP Code', 
   ASP2.SPP1LNum AS 'Dates Row Number', 
   ASP2.SPP2LNum AS 'Row Number', 
   ASP2.Amount AS 'Quantity', 
   ASP2.Price AS 'Special Price', 
   ASP2.Currency AS 'Price Currency', 
   ASP2.Discount AS 'Discount in %', 
   ASP2.UomEntry AS 'UoM Entry', 
   ASP2.LogInstanc AS 'Log Instance'
FROM ASP2 AS ASP2
