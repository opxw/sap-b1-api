   IGN10.DocEntry AS 'Document Internal ID', 
   IGN10.LineSeq AS 'Row Sequence', 
   IGN10.AftLineNum AS 'After Row Number', 
   IGN10.OrderNum AS 'Order Number', 
   IGN10.LineType AS 'Row Type', 
   IGN10.LineText AS 'Row Text', 
   IGN10.LogInstanc AS 'Log Instance', 
   IGN10.ObjType AS 'Object Type'
FROM IGN10 AS IGN10
