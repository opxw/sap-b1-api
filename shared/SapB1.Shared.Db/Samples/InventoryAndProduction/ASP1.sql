SELECT
   ASP1.ItemCode AS 'Item No.', 
   ASP1.CardCode AS 'BP Code', 
   ASP1.LINENUM AS 'Row Number', 
   ASP1.Price AS 'Special Price', 
   ASP1.Currency AS 'Price Currency', 
   ASP1.Discount AS 'Discount %', 
   ASP1.ListNum AS 'Price List No.', 
   ASP1.FromDate AS 'Date From', 
   ASP1.ToDate AS 'Date To', 
   ASP1.AutoUpdt AS 'Auto Update', 
   ASP1.Expand AS 'Item Details', 
   ASP1.LogInstanc AS 'Log Instance'
FROM ASP1 AS ASP1
