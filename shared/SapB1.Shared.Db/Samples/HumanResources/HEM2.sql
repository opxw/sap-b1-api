SELECT
   HEM2.empID AS 'Employee No.', 
   HEM2.line AS 'Education Information Row', 
   HEM2.fromDate AS 'Education from', 
   HEM2.toDate AS 'Education to', 
   HEM2.type AS 'Education Type', 
   HEM2.institute AS 'Institute', 
   HEM2.major AS 'Major', 
   HEM2.diploma AS 'Diploma', 
   HEM2.LogInstanc AS 'Log Instance', 
   HEM2.EncryptIV AS 'Encrypt IV'
FROM HEM2 AS HEM2
