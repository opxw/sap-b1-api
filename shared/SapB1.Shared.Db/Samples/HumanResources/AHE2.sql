SELECT
   AHE2.empID AS 'Employee No.', 
   AHE2.line AS 'Education: Information Row', 
   AHE2.fromDate AS 'Education from', 
   AHE2.toDate AS 'Education to', 
   AHE2.type AS 'Education Type', 
   AHE2.institute AS 'Institute', 
   AHE2.major AS 'Major', 
   AHE2.diploma AS 'Diploma', 
   AHE2.LogInstanc AS 'Log Instance', 
   AHE2.EncryptIV AS 'Encrypt IV'
FROM AHE2 AS AHE2
