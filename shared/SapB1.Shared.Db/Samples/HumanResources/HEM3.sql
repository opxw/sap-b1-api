SELECT
   HEM3.empID AS 'Employee No.', 
   HEM3.line AS 'Employee Review Row', 
   HEM3.date AS 'Employee Review Date', 
   HEM3.reviewDesc AS 'Review Description', 
   HEM3.manager AS 'Manager', 
   HEM3.grade AS 'Grade', 
   HEM3.remarks AS 'Reviews', 
   HEM3.LogInstanc AS 'Log Instance', 
   HEM3.EncryptIV AS 'Encrypt IV'
FROM HEM3 AS HEM3
