SELECT
   HEM5.empID AS 'Employee No.', 
   HEM5.Object AS 'The Object Number', 
   HEM5.Peer AS 'Peer Authorization', 
   HEM5.Manager AS 'Manager Authorization', 
   HEM5.Subord AS 'Subordinate Authorization', 
   HEM5.Dept AS 'Department Authorization', 
   HEM5.Branch AS 'Branch Authorization', 
   HEM5.Team AS 'Team Authorization', 
   HEM5.AC AS 'Cache Access Counter', 
   HEM5.Cmpny AS 'Company Authorization', 
   HEM5.EncryptIV AS 'Encrypt IV'
FROM HEM5 AS HEM5
