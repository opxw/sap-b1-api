SELECT
   AHE3.empID AS 'Employee No.', 
   AHE3.line AS 'Employee Review Row', 
   AHE3.date AS 'Employee Review Date', 
   AHE3.reviewDesc AS 'Review Description', 
   AHE3.manager AS 'Manager', 
   AHE3.grade AS 'Grade', 
   AHE3.remarks AS 'Reviews', 
   AHE3.LogInstanc AS 'Log Instance', 
   AHE3.EncryptIV AS 'Encrypt IV'
FROM AHE3 AS AHE3
