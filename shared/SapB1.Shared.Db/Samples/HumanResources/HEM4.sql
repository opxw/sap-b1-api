SELECT
   HEM4.empID AS 'Employee No.', 
   HEM4.line AS 'Previous Employment Row', 
   HEM4.fromDate AS 'Employment from', 
   HEM4.toDate AS 'Employment to', 
   HEM4.employer AS 'Employer', 
   HEM4.position AS 'Position', 
   HEM4.remarks AS 'Previous Employment', 
   HEM4.LogInstanc AS 'Log Instance', 
   HEM4.EncryptIV AS 'Encrypt IV'
FROM HEM4 AS HEM4
