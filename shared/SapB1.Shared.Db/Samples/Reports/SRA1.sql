SELECT
   SRA1.ActionCode AS 'Action Code', 
   SRA1.ParamCode AS 'Parameter Code', 
   SRA1.KeyString AS 'Parameter Key String', 
   SRA1.KeyNumber AS 'Parameter Key Numerator', 
   SRA1.ValString AS 'Parameter Value String', 
   SRA1.ValNumber AS 'Parameter Value Number', 
   SRA1.ValMoney AS 'Parameter Value Money'
FROM SRA1 AS SRA1
