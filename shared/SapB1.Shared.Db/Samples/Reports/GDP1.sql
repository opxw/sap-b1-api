   GDP1.AbsEntry AS 'Internal Number', 
   GDP1.PfsAbs AS 'Internal Number', 
   GDP1.TableName AS 'Table Name', 
   GDP1.FieldName AS 'Field Name', 
   GDP1.RefObjType AS 'Referenced Object Type', 
   GDP1.Category AS 'Category', 
   GDP1.OrigType AS 'Original Type', 
   GDP1.Type AS 'Type', 
   GDP1.Descr AS 'Description', 
   GDP1.MaxType AS 'Max. Type'
