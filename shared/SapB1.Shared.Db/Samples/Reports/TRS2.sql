SELECT
   TRS2.AbsEntry AS 'Internal Number', 
   TRS2.ObjType AS 'Object Type', 
   TRS2.LineID AS 'Internal Row Number', 
   TRS2.ParamCode AS 'Parameter Code', 
   TRS2.PrmValAmt AS 'Parameter Value Amount', 
   TRS2.PrmValNum AS 'Parameter Value Number', 
   TRS2.PrmValStr AS 'Parameter Value String', 
   TRS2.PrmValTxt AS 'Parameter Value Text'
FROM TRS2 AS TRS2
