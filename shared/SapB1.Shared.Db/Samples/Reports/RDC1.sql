SELECT
   RDC1.DocCode AS 'Doc. Code', 
   RDC1.LineNum AS 'Line Number', 
   RDC1.DocName AS 'Doc. Name', 
   RDC1.LangCode AS 'Language Code', 
   RDC1.Template AS 'Report Template Data', 
   RDC1.CreateDate AS 'Create Date', 
   RDC1.CreateTime AS 'Create Time', 
   RDC1.UpdateDate AS 'Update Date', 
   RDC1.UpdateTime AS 'Update Time'
FROM RDC1 AS RDC1
