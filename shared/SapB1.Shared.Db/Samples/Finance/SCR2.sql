SELECT
   SCR2.RuleID AS 'Rule Identification Number', 
   SCR2.GoalNum AS 'Rule Goal Number', 
   SCR2.TransTpVal AS 'Transaction Type Number', 
   SCR2.TransTpFld AS 'Transaction Type Table Field', 
   SCR2.PrfCntVal AS 'Distribution Rule Code', 
   SCR2.PrfCntFld AS 'Distribution Rule Table Field', 
   SCR2.DebitAct AS 'Debit Account', 
   SCR2.CreditAct AS 'Credit Account', 
   SCR2.RevSides AS 'Revert Debit/Credit Sides', 
   SCR2.SrcTable AS 'Main Source Table', 
   SCR2.SrcField AS 'Main Source Table Field', 
   SCR2.SrcFieldFC AS 'Source Field, Foreign Currency', 
   SCR2.SrcFieldSC AS 'Source Field, System Currency', 
   SCR2.Calc AS 'Calculation Expression', 
   SCR2.CalcFC AS 'Expression for Foreign Calculation', 
   SCR2.CalcSC AS 'Expression for System Calculation', 
   SCR2.CalcCond AS 'Calculation Condition', 
   SCR2.CalcCondFC AS 'Condition for Foreign Calculation', 
   SCR2.CalcCondSC AS 'Condition for System Calculation', 
   SCR2.CurrFld AS 'Table Field with Currency', 
   SCR2.CallProc AS 'Recalculation Stored Procedure Name', 
   SCR2.ExtCond AS 'Extended Special Data'
FROM SCR2 AS SCR2
