SELECT
   OFAA.Code AS 'Code', 
   OFAA.Name AS 'Name', 
   OFAA.DataSource AS 'Data Source', 
   OFAA.UserSign AS 'User Signature', 
   OFAA.LogInstanc AS 'Log Instance', 
   OFAA.CreateDate AS 'Creation Date', 
   OFAA.UserSign2 AS 'Updating User', 
   OFAA.UpdateDate AS 'Date of Update', 
   OFAA.Locked AS 'Locked', 
   OFAA.SnapshotId AS 'Snapshot ID'
FROM OFAA AS OFAA
