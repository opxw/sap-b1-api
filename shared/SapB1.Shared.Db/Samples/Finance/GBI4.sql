SELECT
   GBI4.HistoryId AS 'History Key', 
   GBI4.RowId AS 'Row Number', 
   GBI4.BPNo AS 'BP Number', 
   GBI4.BPName AS 'BP Name', 
   GBI4.CatNo AS 'Category Number', 
   GBI4.Loc AS 'Location Area', 
   GBI4.Tel AS 'Telephone', 
   GBI4.Address AS 'Street/PO Box', 
   GBI4.CreditRank AS 'Credit Rank'
FROM GBI4 AS GBI4
