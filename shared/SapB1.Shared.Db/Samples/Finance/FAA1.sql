SELECT
   FAA1.Code AS 'Code', 
   FAA1.LineNum AS 'Row Number', 
   FAA1.AttrID AS 'Attribute ID', 
   FAA1.AttrName AS 'Attribute Name', 
   FAA1.FieldType AS 'Field Type', 
   FAA1.DefaultVal AS 'Default Value', 
   FAA1.LogInstanc AS 'Log Instance', 
   FAA1.SnapshotId AS 'Snapshot ID'
FROM FAA1 AS FAA1
