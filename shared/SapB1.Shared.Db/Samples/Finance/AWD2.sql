SELECT
   AWD2.AbsEntry AS 'Internal Number', 
   AWD2.EfctFrom AS 'Effective From', 
   AWD2.ValueFrom AS 'Value From', 
   AWD2.Rate AS 'Rate', 
   AWD2.WTCur AS 'Currency', 
   AWD2.LogInstanc AS 'Log Instance', 
   AWD2.LineNum AS 'Row Number', 
   AWD2.SeqNum AS 'Sequence Number'
FROM AWD2 AS AWD2
