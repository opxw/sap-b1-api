SELECT
   OWDD.WddCode AS 'Internal Number', 
   OWDD.WtmCode AS 'Authorization Template', 
   OWDD.OwnerID AS 'Production Code', 
   OWDD.DocEntry AS 'Document Counter', 
   OWDD.ObjType AS 'Object Type', 
   OWDD.DocDate AS 'Posting Date', 
   OWDD.CurrStep AS 'Stage Code', 
   OWDD.Status AS 'Status', 
   OWDD.Remarks AS 'Remarks', 
   OWDD.UserSign AS 'User Signature', 
   OWDD.CreateDate AS 'Production Date', 
   OWDD.CreateTime AS 'Production Time', 
   OWDD.IsDraft AS 'Draft', 
   OWDD.MaxReqr AS 'No. of Authorizers', 
   OWDD.MaxRejReqr AS 'No. of Rejects', 
   OWDD.SrcDocEnt AS 'Source Document Internal ID', 
   OWDD.DraftType AS 'Draft Type', 
   OWDD.DraftEntry AS 'Draft Internal Number', 
   OWDD.BFType AS 'Business Flow Type', 
   OWDD.ProcessID AS 'Approval Process ID', 
   OWDD.ProcesStat AS 'Approval Process Status', 
   OWDD.StpUpdated AS 'Stages Updated'
FROM OWDD AS OWDD
