SELECT
   ADO23.DocEntry AS 'Document Internal ID', 
   ADO23.LineNum AS 'Row Number', 
   ADO23.AssetCode AS 'Selected Asset Code', 
   ADO23.Status AS 'Status', 
   ADO23.Remarks AS 'Remarks', 
   ADO23.Amount AS 'Amount', 
   ADO23.AmountSC AS 'Amount (SC)', 
   ADO23.SerialNo AS 'Serial Number', 
   ADO23.VisOrder AS 'Visual Order', 
   ADO23.LogInstanc AS 'Log Instance', 
   ADO23.ObjectType AS 'Object Type'
FROM ADO23 AS ADO23
