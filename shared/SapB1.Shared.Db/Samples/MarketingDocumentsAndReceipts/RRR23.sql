SELECT
   RRR23.DocEntry AS 'Document Internal ID', 
   RRR23.LineNum AS 'Row Number', 
   RRR23.AssetCode AS 'Selected Asset Code', 
   RRR23.Status AS 'Status', 
   RRR23.Remarks AS 'Remarks', 
   RRR23.Amount AS 'Amount', 
   RRR23.AmountSC AS 'Amount (SC)', 
   RRR23.SerialNo AS 'Serial Number', 
   RRR23.VisOrder AS 'Visual Order', 
   RRR23.LogInstanc AS 'Log Instance', 
   RRR23.ObjectType AS 'Object Type'
FROM RRR23 AS RRR23
