SELECT
   ASC5.SrvcCallId AS 'Service Call No.', 
   ASC5.Line AS 'Row No.', 
   ASC5.ClgID AS 'Activity Code', 
   ASC5.ObjectType AS 'Object Type', 
   ASC5.LogInstanc AS 'Log Instance', 
   ASC5.UserSign AS 'User Signature', 
   ASC5.CreateDate AS 'Creation Date', 
   ASC5.UserSign2 AS 'User Signature 2', 
   ASC5.UpdateDate AS 'Date of Update', 
   ASC5.VisOrder AS 'Visual Order', 
   ASC5.EncryptIV AS 'Encrypt IV'
FROM ASC5 AS ASC5
