SELECT
   OALT.Code AS 'Internal Number', 
   OALT.Name AS 'Name', 
   OALT.Type AS 'Type', 
   OALT.Priority AS 'Priority', 
   OALT.Active AS 'Active Alert', 
   OALT.NumOfParam AS 'No. of Parameters', 
   OALT.ParamData AS 'Parameters', 
   OALT.Params AS 'Parameters', 
   OALT.NumOfDocs AS 'Documents Numbers', 
   OALT.DocsData AS 'Documents', 
   OALT.Docs AS 'Documents', 
   OALT.UserText AS 'MEMO', 
   OALT.QueryId AS 'Query', 
   OALT.FrqncyType AS 'Frequency Type', 
   OALT.FrqncyIntr AS 'Frequency', 
   OALT.ExecDaY AS 'Day of Execution', 
   OALT.ExecTime AS 'Execution Hour', 
   OALT.LastDate AS 'Execution Date', 
   OALT.LastTIME AS 'Execution Time', 
   OALT.NextDate AS 'Next Date', 
   OALT.NextTime AS 'Next Hour', 
   OALT.UserSign AS 'User Signature', 
   OALT.History AS 'Save History', 
   OALT.QCategory AS 'Query Category'
FROM OALT AS OALT
