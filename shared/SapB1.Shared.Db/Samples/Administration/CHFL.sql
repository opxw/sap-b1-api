SELECT
   CHFL.ObjName AS 'Object Name', 
   CHFL.FldIndex AS 'Field Index', 
   CHFL.FldNum AS 'Field No.', 
   CHFL.DispName AS 'Displayed Name', 
   CHFL.GroupBy AS 'Group By', 
   CHFL.Visible AS 'Visible', 
   CHFL.DispDesc AS 'Show Type', 
   CHFL.SortOrder AS 'Sort Order', 
   CHFL.VisIndex AS 'Visual Index'
FROM CHFL AS CHFL
