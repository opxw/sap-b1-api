   OBRW.AbsEntry AS 'Internal Number', 
   OBRW.Name AS 'Browser Widget Name', 
   OBRW.Type AS 'Type', 
   OBRW.Url AS 'Web Site or Extreme Application URL', 
   OBRW.App AS 'Extreme Application Name', 
   OBRW.Title AS 'Title', 
   OBRW.ShowWebTil AS 'Display Web Page Title', 
   OBRW.Size AS 'Widget Size'
FROM OBRW AS OBRW
