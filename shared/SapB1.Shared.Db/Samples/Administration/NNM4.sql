SELECT
   NNM4.ESeries AS 'Electronic Series', 
   NNM4.Series AS 'Series', 
   NNM4.SeriesName AS 'Series Name', 
   NNM4.InitialNum AS 'Initial Number', 
   NNM4.NextNumber AS 'Next Number for Use', 
   NNM4.LastNum AS 'Last Number Allowed', 
   NNM4.Prefix AS 'Prefix', 
   NNM4.ApprovYear AS 'Approval Year', 
   NNM4.ApprovNum AS 'Approval Number', 
   NNM4.Remark AS 'Remarks'
FROM NNM4 AS NNM4
