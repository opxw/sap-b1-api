SELECT
   ACFP.ID AS 'CFOP ID', 
   ACFP.Code AS 'CFOP Code', 
   ACFP.Descrip AS 'Description', 
   ACFP.App AS 'Application', 
   ACFP.Locked AS 'Locked', 
   ACFP.DataSource AS 'Data Source', 
   ACFP.UserSign AS 'User Signature', 
   ACFP.LogInstanc AS 'Log Instance', 
   ACFP.UserSign2 AS 'Updating User', 
   ACFP.UpdateDate AS 'Update Date'
FROM ACFP AS ACFP
