SELECT
   UDO4.Code AS 'Code', 
   UDO4.ColumnNum AS 'Form Column Number', 
   UDO4.SonNum AS 'Child No.', 
   UDO4.ColAlias AS 'Form Column Alias', 
   UDO4.ColDesc AS 'Form Column Description', 
   UDO4.ColIsUsed AS 'Form Column Used or Not', 
   UDO4.ColEdit AS 'Form Column Actived or Not'
FROM UDO4 AS UDO4
