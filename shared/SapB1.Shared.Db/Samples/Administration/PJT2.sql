SELECT
   PJT2.DocEntry AS 'Internal Number', 
   PJT2.StepCode AS 'Step Code', 
   PJT2.LineNum AS 'Line Number', 
   PJT2.Date AS 'Date', 
   PJT2.StartTime AS 'Start Time', 
   PJT2.EndTime AS 'End Time', 
   PJT2.Remarks AS 'Remarks', 
   PJT2.LogInstanc AS 'Log Instance', 
   PJT2.Owner AS 'Owner', 
   PJT2.Duration AS 'Duration'
FROM PJT2 AS PJT2
