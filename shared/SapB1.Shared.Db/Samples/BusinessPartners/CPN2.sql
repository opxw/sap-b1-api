SELECT
   CPN2.CpnNo AS 'Campaign No.', 
   CPN2.CpnLineNum AS 'Campaign Line Number', 
   CPN2.ItemCode AS 'Item No.', 
   CPN2.ItemName AS 'Item Description', 
   CPN2.ItemType AS 'Item Type', 
   CPN2.ItemGrp AS 'Item Group', 
   CPN2.LogIns AS 'Log Instance - History', 
   CPN2.VisOrder AS 'Visual Order'
FROM CPN2 AS CPN2
