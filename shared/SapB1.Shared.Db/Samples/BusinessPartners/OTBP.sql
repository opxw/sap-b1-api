SELECT
   OTBP.CardCode AS 'BP Code', 
   OTBP.CardName AS 'BP Name', 
   OTBP.CntctPrsn AS 'Contact Person', 
   OTBP.Title AS 'Title', 
   OTBP.Position AS 'Position', 
   OTBP.E_Mail AS 'E-Mail', 
   OTBP.Telephone AS 'Telephone', 
   OTBP.Cellolar AS 'Mobile Phone', 
   OTBP.Fax AS 'Fax', 
   OTBP.Address AS 'Address', 
   OTBP.Street AS 'Street/PO Box', 
   OTBP.Block AS 'Block', 
   OTBP.City AS 'City', 
   OTBP.ZipCode AS 'Zip Code', 
   OTBP.County AS 'County', 
   OTBP.Building AS 'Building/Floor/Room'
FROM OTBP AS OTBP
