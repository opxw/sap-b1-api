SELECT
   CPN3.CpnNo AS 'Campaign No.', 
   CPN3.CpnLineNum AS 'Campaign Line Number', 
   CPN3.ParterId AS 'Partners', 
   CPN3.OrlCode AS 'Relationship Code', 
   CPN3.RelatCard AS 'Related BP', 
   CPN3.Memo AS 'Details', 
   CPN3.LogIns AS 'Log Instance - History', 
   CPN3.VisOrder AS 'Visual Order'
FROM CPN3 AS CPN3
