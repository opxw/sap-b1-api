SELECT
   ACP3.CpnNo AS 'Campaign No.', 
   ACP3.CpnLineNum AS 'Campaign Line Number', 
   ACP3.ParterId AS 'Partners', 
   ACP3.OrlCode AS 'Relationship Code', 
   ACP3.RelatCard AS 'Related BP', 
   ACP3.Memo AS 'Details', 
   ACP3.LogIns AS 'Log Instance - History', 
   ACP3.VisOrder AS 'Visual Order'
FROM ACP3 AS ACP3
