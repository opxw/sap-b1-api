SELECT
   ACP2.CpnNo AS 'Campaign No.', 
   ACP2.CpnLineNum AS 'Campaign Line Number', 
   ACP2.ItemCode AS 'Item No.', 
   ACP2.ItemName AS 'Item Description', 
   ACP2.ItemType AS 'Item Type', 
   ACP2.ItemGrp AS 'Item Group', 
   ACP2.LogIns AS 'Log Instance - History', 
   ACP2.VisOrder AS 'Visual Order'
FROM ACP2 AS ACP2
