SELECT
   AWD4.AbsEntry AS 'Internal Number', 
   AWD4.LineId AS 'Row Number', 
   AWD4.WTCode AS 'WTax Code', 
   AWD4.ItemCode AS 'Item No.', 
   AWD4.DateFrom AS 'Effective Date From', 
   AWD4.DateTo AS 'Effective Date To', 
   AWD4.DataSource AS 'Data Source', 
   AWD4.UpdateDate AS 'Date of Update', 
   AWD4.LogInstanc AS 'Log Instance'
FROM AWD4 AS AWD4
