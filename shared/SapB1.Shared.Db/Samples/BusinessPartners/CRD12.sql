   CRD12.CardCode AS 'BP Code', 
   CRD12.ProtCode AS 'Communication Type or Protocol', 
   CRD12.GenType AS 'Generation Type', 
   CRD12.MapID AS 'Electronic Document Format Mapping', 
   CRD12.LogInstanc AS 'Log Instance', 
   CRD12.VatStruct AS 'VAT Structure', 
   CRD12.ParticipID AS 'Participant ID'
