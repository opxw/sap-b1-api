SELECT
   APHA.AbsEntry AS 'Internal Key', 
   APHA.OWNER AS 'Owner', 
   APHA.NAME AS 'Name', 
   APHA.START AS 'Subproject Start Date', 
   APHA.FINISHED AS 'Deduction - Percentage', 
   APHA.ParentID AS 'Parent Subproject', 
   APHA.ProjectID AS 'Project No.', 
   APHA.Code AS 'Subproject No.', 
   APHA.TYP AS 'Subproject Type', 
   APHA.CONTRIB AS 'Subproject Contribution - Percentage', 
   APHA.STATUS AS 'Status', 
   APHA.END AS 'Subproject End Date', 
   APHA.COST AS 'Actual Cost', 
   APHA.PLANNED AS 'Planned Cost', 
   APHA.Level AS 'Depth of Subproject within the project', 
   APHA.DUEDATE AS 'Due Date', 
   APHA.LogInstanc AS 'Log Instance', 
   APHA.UpdateDate AS 'Date of Update', 
   APHA.UserSign AS 'User Signature', 
   APHA.UserSign2 AS 'Updating User', 
   APHA.CreateDate AS 'Production Date', 
   APHA.UpdateTS AS 'Update Full Time'
FROM APHA AS APHA
