SELECT
   NFN5.SeqCode AS 'Sequence Code', 
   NFN5.NFeNoFrom AS 'NF-e No. From', 
   NFN5.NFeNoTo AS 'NF-e No. To', 
   NFN5.Year AS 'Year', 
   NFN5.Reason AS 'Reason for Number Skipping', 
   NFN5.Reply AS 'Reply from the Authority', 
   NFN5.Status AS 'Status', 
   NFN5.VisOrder AS 'Visual Order', 
   NFN5.CreateDate AS 'Creation Date', 
   NFN5.CreateTime AS 'Creation Time', 
   NFN5.UpdateDate AS 'Update Date', 
   NFN5.UpdateTime AS 'Update Time', 
   NFN5.UserSign AS 'User Signature', 
   NFN5.UserSign2 AS 'Updating User'
FROM NFN5 AS NFN5
