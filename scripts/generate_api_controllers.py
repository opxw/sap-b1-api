"""Generate one authorized OPX read controller per BiUan category."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'shared/SapB1.Shared.Db/catalog.generated.json'
OUTPUT = ROOT / 'src/presentation/Controllers/Categories'

ROUTES = {
    'Administration': 'administration', 'Banking': 'banking',
    'Business Partners': 'business-partners', 'Finance': 'finance',
    'Human Resources': 'human-resources',
    'Inventory and Production': 'inventory-and-production',
    'Marketing Documents and Receipts': 'marketing-documents-and-receipts',
    'MRP': 'mrp', 'Reports': 'reports',
    'Sales Opportunities': 'sales-opportunities', 'Service': 'service',
    'Others': 'others',
}


def outputs():
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    if len(catalog['categories']) != len(ROUTES):
        raise ValueError('Unexpected category count')
    files = {}
    for category in catalog['categories']:
        name = category['name']
        namespace = category['namespace']
        route = ROUTES[name]
        lines = ['// <auto-generated> Category route from the local BiUan catalog. </auto-generated>',
                 'using Microsoft.AspNetCore.Authorization;',
                 'using Microsoft.AspNetCore.Mvc;',
                 'using SapB1.Service;', '',
                 'namespace SapB1.Api.Controllers.Categories;', '',
                 f'[Authorize(Policy = "sap-b1.{route}.read")]',
                 f'[Route("api/v1/{route}/tables")]',
                 f'public sealed class {namespace}TablesController(SapTableService service) : ApiController',
                 '{',
                 f'    private const string Category = "{name}";', '',
                 '    [HttpGet]',
                 '    public Task Tables() => OkOrFailAsync(service.TablesAsync(Category));', '',
                 '    [HttpGet("{code}")]',
                 '    public Task Table(string code) => OkOrFailAsync(service.TableAsync(Category, code));', '',
                 '    [HttpGet("{code}/rows")]',
                 '    public Task Rows(string code, [FromQuery] int skip = 0, [FromQuery] int take = 20,',
                 '        CancellationToken cancellationToken = default) =>',
                 '        OkOrFailAsync(service.RowsAsync(Category, code, skip, take, cancellationToken));',
                 '}', '']
        files[OUTPUT / f'{namespace}TablesController.cs'] = '\n'.join(lines)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    files = outputs()
    for path, content in files.items():
        if args.verify:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise ValueError('API controller differs: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    print(json.dumps({'authorizedCategoryControllers': len(files)}))


if __name__ == '__main__':
    main()
