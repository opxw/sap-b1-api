"""Generate fixed, category-scoped table read dispatch from the local DB catalog."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'shared/SapB1.Shared.Db/catalog.generated.json'
OUTPUT = ROOT / 'src/services/Readers'


def outputs():
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    if catalog['summary']['mappedTables'] != 2547:
        raise ValueError('Unexpected mapped table count')
    files = {}
    root_lines = ['// <auto-generated> Fixed table dispatch from the local BiUan catalog. </auto-generated>',
                  'namespace SapB1.Service;', '',
                  'internal static class GeneratedTableReaders', '{',
                  '    internal static readonly IReadOnlyDictionary<string, TableReader> Readers = Build();', '',
                  '    private static IReadOnlyDictionary<string, TableReader> Build()', '    {',
                  '        var readers = new Dictionary<string, TableReader>(StringComparer.Ordinal);']
    for category in catalog['categories']:
        namespace = category['namespace']
        root_lines.append(f'        {namespace}Readers.Register(readers);')
        tables = [table for table in catalog['tables']
                  if table['category'] == category['name'] and table['status'] == 'mapped']
        lines = ['// <auto-generated> Fixed table dispatch from the local BiUan catalog. </auto-generated>',
                 f'using SapB1.Shared.Db.{namespace};', '',
                 'namespace SapB1.Service;', '',
                 f'internal static class {namespace}Readers', '{',
                 '    internal static void Register(Dictionary<string, TableReader> readers)', '    {']
        for table in tables:
            name = table['className'][:-3]
            lines.extend([f'        readers.Add("{table["code"]}", async (options, columns, order, skip, take, ct) =>',
                          '        {', f'            using var db = new {namespace}DbContext(options);',
                          f'            return await TableQuery.ReadAsync(db.{name}, columns, order, skip, take, ct);',
                          '        });'])
        lines.extend(['    }', '}', ''])
        files[OUTPUT / f'{namespace}Readers.cs'] = '\n'.join(lines)
    root_lines.extend(['        return readers;', '    }', '}', ''])
    files[OUTPUT / 'GeneratedTableReaders.cs'] = '\n'.join(root_lines)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    files = outputs()
    for path, content in files.items():
        if args.verify:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise ValueError('API table registry differs: ' + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    print(json.dumps({'categoryReaders': 12, 'mappedTableReaders': 2547}))


if __name__ == '__main__':
    main()
